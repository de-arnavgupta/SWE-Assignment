set -euo pipefail

echo "================================================="
echo "   DevOps System Information & Audit Utility     "
echo "   Student: Arnav Gupta (Roll: 24bcs10063)       "
echo "================================================="

# 1. Variables storing system state
CURRENT_DATE=$(date "+%Y-%m-%d %H:%M:%S")
CURRENT_HOST=$(hostname)
CURRENT_USER=$(whoami)

echo "[INFO] Timestamp : ${CURRENT_DATE}"
echo "[INFO] Hostname  : ${CURRENT_HOST}"
echo "[INFO] User      : ${CURRENT_USER}"
echo "-------------------------------------------------"

# 2. Disk usage inspection (df -h)
echo "=== Disk Usage (df -h) ==="
df -h
echo "-------------------------------------------------"

# 3. Running processes preview (ps)
echo "=== Running Processes Snapshot ==="
if ps aux >/dev/null 2>&1; then
    ps aux | head -n 11
elif ps >/dev/null 2>&1; then
    ps | head -n 11
else
    echo "[PLATFORM NOTE: macOS Sandbox policy restricts direct ps execution in restricted sandboxes; running processes will be captured when executed natively or inside Linux containers]"
fi
echo "-------------------------------------------------"

# 4. User input using read -p
echo "=== Output Directory & File Configuration ==="
read -p "Enter directory name to store audit output [default: system_reports]: " TARGET_DIR
TARGET_DIR=${TARGET_DIR:-system_reports}

read -p "Enter report filename [default: process_audit.txt]: " TARGET_FILE
TARGET_FILE=${TARGET_FILE:-process_audit.txt}

# 5. Create directory using mkdir
echo "[ACTION] Creating directory: ${TARGET_DIR}"
mkdir -p "${TARGET_DIR}"

# 6. Create file using touch
FULL_PATH="${TARGET_DIR}/${TARGET_FILE}"
echo "[ACTION] Initializing file: ${FULL_PATH}"
touch "${FULL_PATH}"

# 7. Write header and redirect running processes information using > output redirection
{
  echo "================================================="
  echo " System Process Audit Report"
  echo " Generated By : Arnav Gupta (24bcs10063)"
  echo " Execution Date: ${CURRENT_DATE}"
  echo " Hostname      : ${CURRENT_HOST}"
  echo " User Session  : ${CURRENT_USER}"
  echo "================================================="
  echo ""
  echo "--- Full Process Snapshot ---"
} > "${FULL_PATH}"

# Append running processes to the report file
if ps aux >> "${FULL_PATH}" 2>/dev/null; then
    :
elif ps >> "${FULL_PATH}" 2>/dev/null; then
    :
else
    echo "Process listing restricted by current macOS sandbox policy." >> "${FULL_PATH}"
    echo "Linux / Native Execution: ps aux provides standard PID, USER, %CPU, %MEM, COMMAND output." >> "${FULL_PATH}"
fi

echo "[SUCCESS] Process information successfully saved to: ${FULL_PATH}"
echo "[VERIFICATION] Total lines written: $(wc -l < "${FULL_PATH}")"
echo "================================================="
